// Browser self-check: call with floating.js and floating.css on a disposable page.
async (source, css) => {
    document.body.innerHTML = '<main><div id="xjtlu-section-selector"><button>Show all</button><label><input type="checkbox" checked>Section one</label></div><div class="xjtlu-tools-panel" id="tm-course-quiz-tools-banner"><select><option>Quiz one</option><option>Quiz two</option></select></div></main><button id="outside">Outside</button>';
    const style = document.createElement('style');
    style.textContent = css;
    document.head.append(style);
    const assert = (value, message) => { if (!value) throw Error(message); };
    const settle = () => new Promise(resolve => setTimeout(resolve, 0));
    const sections = document.getElementById('xjtlu-section-selector');
    const quizzes = document.getElementById('tm-course-quiz-tools-banner');
    let actions = 0;
    sections.querySelector('button').addEventListener('click', () => actions++);
    new Function(source)();
    await settle();
    let toggle = document.querySelector('.xjtlu-floating-toggle');
    let menu = document.getElementById('xjtlu-floating-menu');
    assert(document.querySelectorAll('.xjtlu-floating-toggle').length === 1, 'Duplicate floating buttons');
    assert(menu.hidden && toggle.getAttribute('aria-expanded') === 'false', 'Menu must start closed');
    toggle.click();
    assert(!menu.hidden && toggle.getAttribute('aria-expanded') === 'true', 'Menu did not open');
    assert(menu.contains(sections) && menu.contains(quizzes), 'Course tools did not combine');
    assert(sections.querySelector('input').checked, 'Selection was lost');
    sections.querySelector('button').click();
    assert(actions === 1, 'Original action listener was lost');
    quizzes.querySelector('select').value = 'Quiz two';
    sections.append(document.createTextNode('Saved selection'));
    await settle();
    assert(!menu.hidden && quizzes.querySelector('select').value === 'Quiz two', 'Menu state reset during updates');
    document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    assert(menu.hidden && document.activeElement === toggle, 'Escape must close and return focus');
    toggle.click();
    document.getElementById('outside').click();
    assert(menu.hidden, 'Outside click did not close menu');
    toggle.click();
    const rect = menu.getBoundingClientRect();
    assert(rect.left >= 0 && rect.right <= innerWidth && rect.top >= 0 && rect.bottom <= innerHeight, 'Menu escaped viewport');
    assert(getComputedStyle(toggle.parentElement).position === 'fixed', 'Tools are not floating');
    sections.remove(); quizzes.remove();
    await settle();
    assert(!document.getElementById('xjtlu-floating-tools'), 'Empty menu remains after disabling tools');
    const ams = document.createElement('div');
    ams.id = 'xjtlu-ams-actions';
    ams.innerHTML = '<button disabled>Mark all as present</button><span role="status">Not available</span>';
    const dialog = document.createElement('div');
    dialog.className = 'el-dialog';
    dialog.setAttribute('role', 'dialog');
    dialog.append(ams);
    document.body.append(dialog);
    await settle();
    toggle = document.querySelector('.xjtlu-floating-toggle');
    menu = document.getElementById('xjtlu-floating-menu');
    assert(menu.contains(ams) && ams.querySelector('button').disabled, 'AMS availability changed');
    assert(ams.closest('#xjtlu-floating-tools'), 'AMS cannot recognize its docked toolbar');
    assert(dialog.contains(ams) && dialog.contains(toggle), 'AMS tools escaped the native modal focus trap');
    toggle.click();
    return 'Passed: combined menu, original actions and selections, dynamic updates, Escape/focus, outside click, viewport fit, disabled tools and AMS controls';
}
